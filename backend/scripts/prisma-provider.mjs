import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { config as loadEnv } from 'dotenv';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const schemaDir = path.join(rootDir, 'prisma', 'schema');
const generatedDir = path.join(rootDir, 'prisma', '.generated');

loadEnv({ path: path.join(rootDir, '.env'), quiet: true });
loadEnv({ path: path.join(rootDir, '..', '.env'), quiet: true });

const providerAliases = new Map([
    ['postgres', 'postgresql'],
    ['postgresql', 'postgresql'],
    ['mysql', 'mysql'],
]);

const actionAliases = new Map([
    ['generate', 'generate'],
    ['push', 'push'],
    ['sync', 'sync'],
    ['validate', 'validate'],
]);

const [rawAction = 'generate', rawProvider = process.env.DATABASE_PROVIDER?.trim() || 'postgresql'] =
    process.argv.slice(2);
const action = actionAliases.get(rawAction);
const provider = providerAliases.get(rawProvider.trim().toLowerCase());

if (!action) {
    throw new Error(`Unsupported Prisma action "${rawAction}". Use generate, push, sync, or validate.`);
}

if (!provider) {
    throw new Error(`Unsupported DATABASE_PROVIDER "${rawProvider}". Use postgresql or mysql.`);
}

const schemaPath = await buildSchema(provider);

if (action === 'sync') {
    await runPrisma(['db', 'push', '--accept-data-loss', '--schema', schemaPath]);
    await runPrisma(['generate', '--schema', schemaPath]);
} else if (action === 'push') {
    await runPrisma(['db', 'push', '--schema', schemaPath]);
} else {
    await runPrisma([action, '--schema', schemaPath]);
}

async function buildSchema(databaseProvider) {
    await mkdir(generatedDir, { recursive: true });
    const modelFiles = (await readdir(schemaDir))
        .filter((file) => file.endsWith('.prisma') && file !== 'schema.prisma')
        .sort((a, b) => {
            if (a === 'enums.prisma') {
                return -1;
            }
            if (b === 'enums.prisma') {
                return 1;
            }
            return a.localeCompare(b);
        });

    const schema = [
        '// Generated by scripts/prisma-provider.mjs. Do not edit or commit.',
        '',
        'generator client {',
        '  provider     = "prisma-client"',
        '  output       = "../../src/generated/prisma-client"',
        '  moduleFormat = "cjs"',
        '}',
        '',
        'datasource db {',
        `  provider = "${databaseProvider}"`,
        '}',
        '',
        ...(await Promise.all(
            modelFiles.map((file) => readFile(path.join(schemaDir, file), 'utf8')),
        )),
    ].join('\n');

    const schemaPath = path.join(generatedDir, `schema.${databaseProvider}.prisma`);
    await writeFile(schemaPath, schema);

    return schemaPath;
}

async function runPrisma(args) {
    await new Promise((resolve, reject) => {
        const prismaCli = path.join(rootDir, 'node_modules', 'prisma', 'build', 'index.js');
        const child = spawn(process.execPath, [prismaCli, ...args], {
            cwd: rootDir,
            env: {
                ...process.env,
                DATABASE_URL: getProviderUrl(provider),
                DATABASE_PROVIDER: provider,
            },
            stdio: 'inherit',
        });

        child.on('error', reject);
        child.on('exit', (code) => {
            if (code === 0) {
                resolve();
            } else {
                reject(new Error(`prisma ${args.join(' ')} exited with code ${code}`));
            }
        });
    });
}

function getProviderUrl(databaseProvider) {
    const candidates =
        databaseProvider === 'mysql'
            ? [process.env.DATABASE_URL, process.env.MYSQL_DATABASE_URL]
            : [
                  process.env.DATABASE_URL,
                  process.env.POSTGRES_DATABASE_URL,
                  process.env.TEMPLATE_DB_URL,
              ];
    const url = candidates.find((candidate) =>
        candidate ? urlMatchesProvider(candidate, databaseProvider) : false,
    );

    if (!url) {
        throw new Error(
            `No valid ${databaseProvider} database URL configured. Set DATABASE_URL or the provider-specific URL.`,
        );
    }

    return url;
}

function urlMatchesProvider(url, databaseProvider) {
    if (databaseProvider === 'mysql') {
        return url.startsWith('mysql://');
    }

    return url.startsWith('postgresql://') || url.startsWith('postgres://');
}
